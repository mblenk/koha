sub build_marc_record {
    my (%a) = @_;

    my $record = MARC::Record->new;
    $record->encoding('UTF-8');
    $record->leader('00000nam a2200000 a 4500');

    if ( $a{author} ) {
        $record->append_fields( MARC::Field->new( '100', '1', ' ', a => "$a{author}," ) );
    } elsif ( $a{corporate} ) {
        $record->append_fields( MARC::Field->new( '110', '2', ' ', a => $a{corporate} ) );
    }

    my @title_subs = ( a => $a{title} . ( $a{subtitle} ? ' :' : '' ) );
    push @title_subs, ( b => "$a{subtitle} /" ) if $a{subtitle};
    my $ind1 = $a{author} ? '1' : '0';
    $record->append_fields( MARC::Field->new( '245', $ind1, '0', @title_subs ) );

    if ( $a{place} || $a{publisher} || $a{year} ) {
        $record->append_fields(
            MARC::Field->new(
                '264', ' ', '1',
                ( $a{place}     ? ( a => "$a{place} :" )    : () ),
                ( $a{publisher} ? ( b => "$a{publisher}," ) : () ),
                ( $a{year}      ? ( c => $a{year} )         : () ),
            )
        );
    }

    $record->append_fields( MARC::Field->new( '300', ' ', ' ', a => $a{pages} ) )    if $a{pages};
    $record->append_fields( MARC::Field->new( '020', ' ', ' ', a => $a{isbn} ) )     if $a{isbn};
    $record->append_fields( MARC::Field->new( '041', '0', ' ', a => 'eng' ) )        if $a{lang_note};
    $record->append_fields( MARC::Field->new( '500', ' ', ' ', a => $a{note} ) )     if $a{note};
    $record->append_fields( MARC::Field->new( '520', ' ', ' ', a => $a{summary} ) )  if $a{summary};
    $record->append_fields( MARC::Field->new( '521', ' ', ' ', a => $a{audience} ) ) if $a{audience};

    if ( $a{series} ) {
        $record->append_fields( MARC::Field->new( '490', '1', ' ', a => $a{series}, v => ( $a{series_vol} // '1' ) ) );
        $record->append_fields(
            MARC::Field->new( '830', ' ', '0', a => "$a{series}.", v => ( $a{series_vol} // '1' ) ) );
    }

    for my $subj ( @{ $a{subjects} // [] } ) {
        $record->append_fields( MARC::Field->new( '650', ' ', '0', a => $subj ) );
    }

    $record->append_fields( MARC::Field->new( '700', '1', ' ', a => "$a{author2}," ) ) if $a{author2};
    $record->append_fields( MARC::Field->new( '942', ' ', ' ', c => 'BK' ) );

    return $record;
}

sub gen_isbn {
    my $p = $isbn_prefixes[ int( rand( scalar @isbn_prefixes ) ) ];
    return $p . sprintf( '%06d', int( rand(999999) ) );
}

