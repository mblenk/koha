# generate_rich_sample_biblios.pl
#
# Insert ~4000 varied biblio records (fiction + non-fiction) for testing
# semantic search and LLM response quality.
#
# Usage:
#   perl misc/devel/generate_rich_sample_biblios.pl [--delete]
#
# --delete   Remove all existing biblios before inserting.

use strict;
use warnings;

use Getopt::Long qw( GetOptions );
use Koha::Script;
use C4::Biblio qw( AddBiblio DelBiblio );
use C4::Context;
use MARC::Record;
use MARC::Field;
use Koha::Biblios;
use Koha::Items;

my $delete_first = 0;
GetOptions( 'delete' => \$delete_first );

if ($delete_first) {
    print "Deleting existing biblios...\n";
    Koha::Items->search->delete( { skip_record_index => 1 } );
    my @biblionumbers = Koha::Biblios->search->get_column('biblionumber');
    DelBiblio( $_, { skip_record_index => 1 } ) for @biblionumbers;
    print "Done.\n";
}

